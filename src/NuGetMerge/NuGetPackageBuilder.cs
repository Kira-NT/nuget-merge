using System.Collections.Immutable;
using System.Collections.ObjectModel;
using System.Diagnostics.CodeAnalysis;
using NuGet.Common;
using NuGet.Frameworks;
using NuGet.Packaging;
using NuGet.Packaging.Core;

namespace NuGetMerge;

public sealed class NuGetPackageBuilder
{
    private readonly IReadOnlyList<string> _excludedDependencies;
    private readonly PackageBuilder _package;

    public NuGetPackageBuilder() : this(deterministic: false, excludedDependencies: Array.Empty<string>(), logger: null)
    {
        _excludedDependencies = Array.Empty<string>();
    }

    public NuGetPackageBuilder(bool deterministic, IReadOnlyList<string> excludedDependencies, ILogger? logger)
    {
        _excludedDependencies = excludedDependencies;
        _package = new(deterministic, logger);
    }

    public static NuGetPackageBuilder Merge(IEnumerable<string> packagePaths, bool deterministic = false, ILogger? logger = null)
        => Merge(packagePaths.Select(File.OpenRead), deterministic, logger);

    public static NuGetPackageBuilder Merge(IEnumerable<Stream> packages, bool deterministic = false, ILogger? logger = null)
        => Merge(packages.Select(x => new PackageArchiveReader(x)), deterministic, logger);

    public static NuGetPackageBuilder Merge(IEnumerable<IPackageCoreReader> packages, bool deterministic = false, ILogger? logger = null)
    {
        var excludeSelfDeps = packages
            .Select(item => item.GetIdentity().Id)
            .Distinct()
            .ToImmutableList();

        NuGetPackageBuilder builder = new(deterministic, excludeSelfDeps, logger);

        foreach (IPackageCoreReader packageReader in packages)
            builder.PopulateFrom(packageReader);        

        return builder;
    }

    public void AddFile(string fileName, Stream content)
    {
        using Stream file = content;
        long fileLength = file.CanSeek ? (file.Length - file.Position) : 0;

        // NuGet.Packaging performs a pre-pass on some provided files (like icons) to validate them
        // before saving, and disposes their respective streams along the way, which immediately
        // causes an ObjectDisposedException. Thanks, I guess. That's why we extend MemoryStream
        // to rewind itself to the start instead of following the standard dispose logic.
        PersistentMemoryStream buffer = new((ulong)fileLength < int.MaxValue ? (int)fileLength : 0);
        file.CopyTo(buffer);
        buffer.Position = 0;

        _package.Files.Add(new PhysicalPackageFile(buffer) { TargetPath = fileName });
    }

    public void PopulateFrom(string packagePath)
    {
        using PackageArchiveReader archiveReader = new(packagePath);
        PopulateFrom(archiveReader);
    }

    public void PopulateFrom(Stream packageStream)
    {
        using PackageArchiveReader archiveReader = new(packageStream);
        PopulateFrom(archiveReader);
    }

    public void PopulateFrom(IPackageCoreReader packageReader)
    {
        Manifest manifest = Manifest.ReadFrom(packageReader.GetNuspec(), validateSchema: false);
        Lazy<NuGetFramework?>? defaultFramework = packageReader is IPackageContentReader x ? new(() => GetDefaultFramework(x)) : null;
        PopulateMetadataFrom(manifest.Metadata, defaultFramework);
        PopulateFilesFrom(packageReader);
    }

    public void PopulateFilesFrom(IPackageCoreReader packageReader)
    {
        foreach (string fileName in packageReader.GetFiles())
        {
            if (IsAutoGeneratedFile(fileName))
                continue;

            if (_package.Files.Any(x => fileName.Equals(x.Path, StringComparison.OrdinalIgnoreCase)))
                continue;

            AddFile(fileName, packageReader.GetStream(fileName));
        }
    }

    public void PopulateMetadataFrom(IPackageMetadata metadata)
        => PopulateMetadataFrom(metadata, default(Lazy<NuGetFramework?>));

    public void PopulateMetadataFrom(IPackageMetadata metadata, NuGetFramework? defaultFramework)
        => PopulateMetadataFrom(metadata, defaultFramework is null ? null : new Lazy<NuGetFramework?>(() => defaultFramework, isThreadSafe: true));

    private void PopulateMetadataFrom(IPackageMetadata metadata, Lazy<NuGetFramework?>? defaultFramework)
    {
        PackageBuilder package = _package;
        if (string.IsNullOrEmpty(package.Id) && metadata.Id is { } id)
            package.Id = id;

        if (string.IsNullOrEmpty(package.Title) && metadata.Title is { } title)
            package.Title = title;

        if (string.IsNullOrEmpty(package.Summary) && metadata.Summary is { } summary)
            package.Summary = summary;

        if (string.IsNullOrEmpty(package.Description) && metadata.Description is { } description)
            package.Description = description;

        if (string.IsNullOrEmpty(package.Icon) && metadata.Icon is { } icon)
            package.Icon = icon;

        if (string.IsNullOrEmpty(package.ReleaseNotes) && metadata.ReleaseNotes is { } releaseNotes)
            package.ReleaseNotes = releaseNotes;

        if (string.IsNullOrEmpty(package.Readme) && metadata.Readme is { } readme)
            package.Readme = readme;

        if (string.IsNullOrEmpty(package.Copyright) && metadata.Copyright is { } copyright)
            package.Copyright = copyright;

        if (string.IsNullOrEmpty(package.Language) && metadata.Language is { } language)
            package.Language = language;

        package.Version ??= metadata.Version;
        package.MinClientVersion ??= metadata.MinClientVersion;
        package.LicenseMetadata ??= metadata.LicenseMetadata;
        package.Repository ??= metadata.Repository;
        package.IconUrl ??= metadata.IconUrl;
        package.LicenseUrl ??= metadata.LicenseUrl;
        package.ProjectUrl ??= metadata.ProjectUrl;

        package.Serviceable |= metadata.Serviceable;
        package.DevelopmentDependency |= metadata.DevelopmentDependency;
        package.RequireLicenseAcceptance |= metadata.RequireLicenseAcceptance;
        package.EmitRequireLicenseAcceptance = package.RequireLicenseAcceptance;

        package.Tags.AddRange(metadata.Tags?.Split(' ', StringSplitOptions.RemoveEmptyEntries) ?? []);
        package.Authors.AddRange(metadata.Authors ?? []);
        package.Owners.AddRange(metadata.Owners ?? []);
        package.PackageTypes.AddRange((metadata.PackageTypes ?? []).Except(package.PackageTypes));

        AddContentFiles(package.ContentFiles, metadata.ContentFiles);
        AddFrameworkReferences(package.FrameworkReferences, metadata.FrameworkReferences);
        AddDependencyGroups(package.DependencyGroups, metadata.DependencyGroups.Select(x => x.TargetFramework is null ? new(defaultFramework?.Value, x.Packages) : x));
        AddAssemblyReferences(package.PackageAssemblyReferences, metadata.PackageAssemblyReferences.Select(x => x.TargetFramework is null ? new(defaultFramework?.Value, x.References) : x));
    }

    public void Save(string path)
    {
        using FileStream stream = File.Create(path);
        Save(stream);
    }

#if NET5_0_OR_GREATER
    // NuGet.Packaging is absolutely not trimmer-friendly. In quite a few ways, actually.
    // Here, for example, when we try to save a package, the library attempts to infer
    // the minimum applicable manifest version based on the properties we set.
    // To do that, it looks for `ManifestVersionAttribute`, because of course
    // we need reflection to check if a couple of properties are null or not.
    // And if we don't preserve those properties (or rather their metadata)
    // ourselves, NativeAOT builds of the tool would just crash.
    // Fun.
    [DynamicDependency(nameof(ManifestMetadata.Copyright), typeof(ManifestMetadata))]
    [DynamicDependency(nameof(ManifestMetadata.ReleaseNotes), typeof(ManifestMetadata))]
    [DynamicDependency(nameof(ManifestMetadata.MinClientVersionString), typeof(ManifestMetadata))]
#endif
    public void Save(Stream stream)
        => _package.Save(stream);

    private static NuGetFramework? GetDefaultFramework(IPackageContentReader package)
    {
        // Previous versions of NuGet packages sometimes didn't explicitly specify
        // a framework for a given dependency group if it could be inferred implicitly.
        // That's exactly what we do here - we infer the "default" framework for the provided package.
        // The default framework is the only framework ever mentioned by the package.
        // If there's more than one or none at all, we return `null`.
        IEnumerable<NuGetFramework> frameworks = package
            .GetLibItems().Select(x => x.TargetFramework)
            .Concat(package.GetBuildItems().Select(x => x.TargetFramework))
            .Concat(package.GetContentItems().Select(x => x.TargetFramework))
            .Concat(package.GetToolItems().Select(x => x.TargetFramework))
            .Concat(package.GetFrameworkItems().Select(x => x.TargetFramework))
            .Where(x => x is { IsUnsupported: false });

        using IEnumerator<NuGetFramework> enumerator = frameworks.GetEnumerator();
        if (!enumerator.MoveNext())
            return null;

        NuGetFramework? defaultFramework = enumerator.Current;
        while (enumerator.MoveNext())
        {
            if (!NuGetFrameworkFullComparer.Instance.Equals(enumerator.Current, defaultFramework))
                return null;
        }
        return defaultFramework;
    }

    private void AddDependencyGroups(Collection<PackageDependencyGroup> mergedGroups, IEnumerable<PackageDependencyGroup> newGroups)
    {
        foreach (PackageDependencyGroup newGroup in newGroups)
        {
            int oldGroupIndex = FindIndex(mergedGroups, d => d.TargetFramework == newGroup.TargetFramework);
            if (oldGroupIndex < 0)
            {
                mergedGroups.Add(newGroup);
                continue;
            }

            PackageDependency[] newGroupPackages = newGroup.Packages
                .Where(pkg => !_excludedDependencies.Contains(pkg.Id))
                .ToArray();

            PackageDependency[] packages = mergedGroups[oldGroupIndex].Packages.Concat(newGroupPackages)
                .GroupBy(static x => x.Id, StringComparer.OrdinalIgnoreCase)
                .Select(static x => x.First())
                .ToArray();

            mergedGroups[oldGroupIndex] = new PackageDependencyGroup(newGroup.TargetFramework, packages);
        }
    }

    private static void AddFrameworkReferences(Collection<FrameworkAssemblyReference> references, IEnumerable<FrameworkAssemblyReference> newReferences)
    {
        if (references.Count == 0)
        {
            references.AddRange(newReferences);
            return;
        }

        foreach (FrameworkAssemblyReference newReference in newReferences)
        {
            if (!references.Any(f => f.AssemblyName.Equals(newReference.AssemblyName, StringComparison.OrdinalIgnoreCase)))
                references.Add(newReference);
        }
    }

    private static void AddAssemblyReferences(ICollection<PackageReferenceSet> sets, IEnumerable<PackageReferenceSet> newSets)
    {
        if (sets.Count == 0)
        {
            sets.AddRange(newSets);
            return;
        }

        // I have no idea why NuGet.Packaging sometimes uses ICollection<T> and
        // sometimes - Collection<T> (which is basically List<T>, but worse).
        // In fact, PackageBuilder.PackageAssemblyReferences **is** backed by
        // Collection<T>, similar to other properties. However, because its
        // public-facing signature is ICollection<T>, we now need to handle
        // the scenario where PackageAssemblyReferences is not an IList<T>,
        // in case something changes under the hood without us knowing.
        //
        // So, this is essentially a stub for a worst-case scenario I don't expect us to ever hit.
        if (sets is not IList<PackageReferenceSet> oldSets)
        {
            PackageReferenceSet[] uniqueSets = sets.Concat(newSets)
                .GroupBy(x => x.TargetFramework, x => x.References)
                .Select(x => new PackageReferenceSet(
                    x.Key,
                    new HashSet<string>(x.SelectMany(y => y), StringComparer.OrdinalIgnoreCase)
                ))
                .ToArray();

            sets.Clear();
            sets.AddRange(uniqueSets);
            return;
        }

        foreach (PackageReferenceSet newSet in newSets)
        {
            int oldSetIndex = FindIndex(oldSets, x => x.TargetFramework == newSet.TargetFramework);
            if (oldSetIndex < 0)
            {
                sets.Add(newSet);
                continue;
            }

            HashSet<string> uniqueReferences = new(oldSets[oldSetIndex].References.Concat(newSet.References), StringComparer.OrdinalIgnoreCase);
            oldSets[oldSetIndex] = new PackageReferenceSet(newSet.TargetFramework, uniqueReferences);
        }
    }

    private static void AddContentFiles(ICollection<ManifestContentFiles> contentFiles, IEnumerable<ManifestContentFiles> newContentFiles)
    {
        Dictionary<string, ManifestContentFiles> knownFiles = new(StringComparer.OrdinalIgnoreCase);
        foreach (ManifestContentFiles contentFile in contentFiles)
        {
            if (contentFile.Include is not null)
                knownFiles[contentFile.Include] = contentFile;
        }

        foreach (ManifestContentFiles contentFile in newContentFiles)
        {
            if (contentFile.Include is null)
                continue;

            if (knownFiles.TryGetValue(contentFile.Include, out ManifestContentFiles? existingFile))
            {
                if (string.IsNullOrEmpty(existingFile.Exclude))
                    existingFile.Exclude = contentFile.Exclude;

                if (string.IsNullOrEmpty(existingFile.BuildAction))
                    existingFile.BuildAction = contentFile.BuildAction;

                if (string.IsNullOrEmpty(existingFile.CopyToOutput))
                    existingFile.CopyToOutput = contentFile.CopyToOutput;

                if (string.IsNullOrEmpty(existingFile.Flatten))
                    existingFile.Flatten = contentFile.Flatten;
            }
            else
            {
                contentFiles.Add(contentFile);
                knownFiles.Add(contentFile.Include, contentFile);
            }
        }
    }

    private static bool IsAutoGeneratedFile(string fileName)
    {
        // If we stumble upon a directory, just ignore it - it's not a real file.
        if (string.IsNullOrEmpty(fileName) || fileName[fileName.Length - 1] is '/' or '\\')
            return true;

        // A *.nuspec file located in the root of the package will be regenerated by PackageBuilder.
        if (PackageHelper.IsNuspec(fileName))
            return fileName.LastIndexOfAny('/', '\\') <= 0;

        // /_rels/**/*, /package/**/*, and /[Content_Types].xml are all parts of the spec and
        // should be generated by PackageBuilder, not provided by the user.
        ReadOnlySpan<char> filePath = fileName[0] is '/' or '\\' ? fileName.AsSpan(1) : fileName;
        int rootLength = filePath.IndexOfAny('/', '\\');
        ReadOnlySpan<char> root = filePath.Slice(0, rootLength >= 0 ? rootLength : filePath.Length);
        return root is "_rels" or "package" or "[Content_Types].xml";
    }

    private static int FindIndex<T>(IList<T> list, Func<T, bool> predicate)
    {
        int count = list.Count;
        for (int i = 0; i < count; i++)
        {
            if (predicate(list[i]))
                return i;
        }
        return -1;
    }
}

file sealed class PersistentMemoryStream : MemoryStream
{
    public PersistentMemoryStream(int capacity) : base(capacity) { }

    protected override void Dispose(bool disposing) => Position = 0;
}
